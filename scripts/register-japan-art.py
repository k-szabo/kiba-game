"""Register native Japanese enemy sheets. Analyze alpha without modifying pixels."""
import argparse
import json
import runpy
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ROLES = ('guard', 'archer', 'shield', 'mage', 'raised')
HELPER = runpy.run_path(str(ROOT / 'scripts/register-shadow-art.py'))
components, polygon = HELPER['components'], HELPER['polygon']


def register(role):
    path = 'assets/images/enemies/japan-' + role + '-v5.png'
    image = Image.open(ROOT / path)
    assert image.mode == 'RGBA', (path, 'native alpha required')
    alpha = np.asarray(image.getchannel('A'))
    groups = components(alpha >= 8)
    major = groups[:12]
    mass = lambda g: sum(b-a for _, a, b in g)
    assert len(major) == 12 and mass(major[-1]) > 2000, (path, 'twelve independent poses required')
    assert len(groups) == 12 or mass(groups[12]) < 2000, (path, 'unexpected extra character')
    vertical = sorted(major, key=lambda g: sum(y*(b-a) for y, a, b in g) / mass(g))
    ordered = []
    for row in range(4):
        ordered += sorted(vertical[row*3:row*3+3], key=lambda g: min(a for _, a, _ in g))
    frames = []
    for index, own in enumerate(ordered):
        rows = {}
        for y, start, end in own:
            old = rows.get(y, (image.width, 0))
            rows[y] = min(start, old[0]), max(end, old[1])
        spans = {}
        for y, (start, end) in rows.items():
            block = y // 4
            old = spans.get(block, (image.width, 0))
            spans[block] = min(start, old[0]), max(end, old[1])
        rows = {y: spans[y // 4] for y in range(min(rows), max(rows)+1) if y // 4 in spans}
        # Alpha silhouettes, rather than ideal grid cells, retain weapon tips
        # crossing a cell boundary without drawing the neighbouring character.
        for other in ordered:
            if other is not own:
                assert all(y not in rows or end <= rows[y][0] or start >= rows[y][1] for y, start, end in other), (path, index, 'silhouette includes another pose')
        left, right = min(a for a, _ in rows.values()), max(b for _, b in rows.values())
        top, bottom = min(rows), max(rows)+1
        feet = [span for y, span in rows.items() if y >= bottom-7]
        anchor_x = (min(a for a, _ in feet) + max(b for _, b in feet)) / 2
        x0, y0 = max(0, left-2), max(0, top-2)
        x1, y1 = min(image.width, right+2), min(image.height, bottom+2)
        frames.append(dict(x=x0, y=y0, w=x1-x0, h=y1-y0,
                           anchorX=anchor_x, anchorY=bottom-1,
                           visibleBounds=[left, top, right, bottom], outlines=[polygon(rows)],
                           pose=('walk' if index < 6 else 'attack') + str(index % 6)))
    body_height = int(np.median([f['visibleBounds'][3] - f['visibleBounds'][1] for f in frames[:6]]))
    for frame in frames:
        frame['bodyHeight'] = body_height
    # Hold the shield's late preparation, then show its native thrust at the
    # existing damage instant instead of displaying contact during the warning.
    attack_order = [6, 7, 7, 8, 9, 11] if role == 'shield' else list(range(6, 12))
    return dict(image='japan' + role.capitalize(), path=path, width=image.width, height=image.height,
                facing=1, frames=frames, attackOrder=attack_order, walk=frames[:6], attack=[frames[i] for i in attack_order])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    definitions = {role: register(role) for role in ROLES}
    path = ROOT / 'assets/js/art-data.js'
    source = path.read_text(encoding='utf-8')
    compact = {role: {key: value for key, value in definition.items() if key not in ('walk', 'attack')} for role, definition in definitions.items()}
    block = ('// BEGIN JAPAN ENEMY ATLAS — generated by scripts/register-japan-art.py\nconst ART_JAPAN='
             + json.dumps(compact, separators=(',', ':'))
             + ';\nfor(const definition of Object.values(ART_JAPAN)){definition.walk=definition.frames.slice(0,6);definition.attack=definition.attackOrder.map(index=>definition.frames[index]);}\n// END JAPAN ENEMY ATLAS')
    if '// BEGIN JAPAN ENEMY ATLAS' in source:
        start = source.index('// BEGIN JAPAN ENEMY ATLAS')
        end = source.index('// END JAPAN ENEMY ATLAS', start) + len('// END JAPAN ENEMY ATLAS')
        result = source[:start] + block + source[end:]
    else:
        result = source.rstrip() + '\n' + block + '\n'
    if args.check:
        assert source == result, 'Japanese enemy registration is stale'
    else:
        path.write_text(result, encoding='utf-8', newline='\n')
    print('PASS: five native Japanese enemy sheets, twelve full poses each, fixed scale and foot anchors' + (' checked.' if args.check else ' registered.'))


if __name__ == '__main__':
    main()

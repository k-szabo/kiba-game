"""Derive native-alpha atlas bounds/foot registration without rewriting source pixels."""
import hashlib
import json
from pathlib import Path
import sys
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SPECS = {
    'crossbow': ('ninjaCrossbow', 'assets/images/enemies/shadow-ninja-crossbow-v1.png', 3, 2),
    'shuriken': ('ninjaShuriken', 'assets/images/enemies/shadow-ninja-shuriken-v1.png', 3, 2),
    'ninjutsu': ('ninjaNinjutsu', 'assets/images/enemies/shadow-ninja-ninjutsu-v1.png', 3, 2),
    'assassin': ('ninjaAssassin', 'assets/images/enemies/shadow-ninja-assassin-v1.png', 3, 2),
    'leader': ('ninjaLeader', 'assets/images/enemies/shadow-ninja-leader-v1.png', 4, 2),
    'momoHook': ('momoHook', 'assets/images/momo-hook-v1.png', 2, 2),
}

def registration():
    result, hashes = {}, []
    for name, (image_key, file, columns, rows) in SPECS.items():
        image = Image.open(ROOT / file)
        assert image.mode == 'RGBA', f'{file}: native RGBA required'
        alpha = image.getchannel('A')
        assert alpha.getextrema()[0] == 0, f'{file}: transparent margins required'
        frames, heights = [], []
        for index in range(columns * rows):
            col, row = index % columns, index // columns
            x, y = round(col * image.width / columns), round(row * image.height / rows)
            right, bottom = round((col + 1) * image.width / columns), round((row + 1) * image.height / rows)
            mask = alpha.crop((x, y, right, bottom)).point(lambda a: 255 if a > 16 else 0)
            bounds = mask.getbbox()
            assert bounds and bounds[0] > 0 and bounds[1] > 0 and bounds[2] < right-x and bounds[3] < bottom-y, f'{file}: frame {index} clipped/empty'
            feet = mask.crop((0, max(0, bounds[3]-16), right-x, bounds[3])).getbbox()
            anchor_x = x + (feet[0] + feet[2]) / 2
            heights.append(bounds[3] - bounds[1])
            frames.append(dict(x=x, y=y, w=right-x, h=bottom-y, anchorX=anchor_x,
                               anchorY=y+bounds[3], visibleBounds=[x+bounds[0], y+bounds[1], x+bounds[2], y+bounds[3]]))
        # Casting Momo has no overhead prop; use that frame as his body-height
        # reference. Crouching/jumping poses retain the same anatomical scale.
        body_height = heights[1 if name == 'momoHook' else 0]
        for frame in frames:
            frame['bodyHeight'] = body_height
        result[name] = dict(image=image_key, facing=1, frames=frames)
        hashes.append(hashlib.sha256((ROOT / file).read_bytes()).hexdigest())
    icon = ROOT / 'assets/images/ui/grappling-hook-v1.png'
    image = Image.open(icon)
    assert image.mode == 'RGBA' and image.getchannel('A').getextrema()[0] == 0
    bounds = image.getchannel('A').point(lambda a: 255 if a > 16 else 0).getbbox()
    assert bounds and bounds[0] > 0 and bounds[1] > 0 and bounds[2] < image.width and bounds[3] < image.height
    item = dict(name='islands.hook', realm=0, image='grapplingHook', x=bounds[0], y=bounds[1], w=bounds[2]-bounds[0], h=bounds[3]-bounds[1])
    hashes.append(hashlib.sha256(icon.read_bytes()).hexdigest())
    return ("/* Generated by scripts/register-islands-art.py; native alpha preserved; sources: " + ','.join(hashes) + " */\n'use strict';\nconst ART_SHADOW_NINJAS=" + json.dumps(result, separators=(',', ':')) + ";\nART_INVENTORY.items.grapplingHook=" + json.dumps(item, separators=(',', ':')) + ';\n')

target = ROOT / 'assets/js/shadow-ninja-art-data.js'
content = registration()
if '--check' in sys.argv:
    assert target.read_text(encoding='utf-8') == content, 'Island atlas registration is stale'
    print('PASS: six native-alpha actor atlases, full weapon bounds, foot anchors and hook inventory crop.')
else:
    target.write_text(content, encoding='utf-8', newline='\n')
    print('Registered island atlases without rewriting source images.')

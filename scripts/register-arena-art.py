"""Register native arena images using alpha masks; never rewrite image pixels."""
import argparse,json,runpy
from pathlib import Path
import numpy as np
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
helper=runpy.run_path(str(ROOT/'scripts/register-shadow-art.py'))
components,polygon=helper['components'],helper['polygon']
SPECS={
 'captain':('arena-captain-v1.png','arenaCaptain',6,3,435,[(271,494),(803,488),(1290,494),(288,957),(785,957),(1275,979)]),
 'serpent':('arena-serpent-v1.png','arenaSerpent',6,3,380,[(273,492),(766,489),(1270,494),(270,946),(770,949),(1270,952)]),
 'cyclops':('arena-cyclops-v1.png','arenaCyclops',6,3,375,[(287,504),(776,502),(1262,503),(227,964),(815,965),(1250,963)]),
 'minions':('arena-minions-v1.png','arenaMinions',8,4,370,[(220,429),(618,428),(1050,428),(1520,427),(205,849),(600,842),(1045,842),(1450,842)]),
 'fiaCasting':('fia-arena-casting-v1.png','fiaArenaCasting',4,2,470,[(440,491),(1165,493),(440,992),(1205,1007)]),
 'fiaWalk':('fia-arena-walk-v1.png','fiaArenaWalk',4,2,470,[(500,483),(1205,488),(510,984),(1220,986)]),
 'fiaYield':('fia-arena-yield-v1.png','fiaArenaYield',4,2,470,[(435,517),(1170,528),(450,974),(1190,997)])
}
def register(key,spec):
 filename,image_key,count,cols,body,anchors=spec
 path='assets/images/enemies/'+filename; im=Image.open(ROOT/path)
 assert im.mode=='RGBA'
 groups=components(np.asarray(im.getchannel('A'))>=8)
 major=groups[:count]
 assert min(sum(b-a for y,a,b in g) for g in major)>10000
 vertical=sorted(major,key=lambda g:sum(y*(b-a) for y,a,b in g)/sum(b-a for y,a,b in g))
 ordered=[]
 for row in range(count//cols):ordered+=sorted(vertical[row*cols:(row+1)*cols],key=lambda g:min(a for y,a,b in g))
 frames=[]
 for index,g in enumerate(ordered):
  rows={}
  for y,a,b in g:
   old=rows.get(y,(im.width,0));rows[y]=(min(a,old[0]),max(b,old[1]))
  # Four-row conservative hulls keep every original alpha pixel and all weapon tips.
  spans={}
  for y,(a,b) in rows.items():
   block=y//4;old=spans.get(block,(im.width,0));spans[block]=(min(a,old[0]),max(b,old[1]))
  hull={y:spans[y//4] for y in range(min(rows),max(rows)+1) if y//4 in spans}
  x0=max(0,min(a for a,b in rows.values())-3);x1=min(im.width,max(b for a,b in rows.values())+3)
  y0=max(0,min(rows)-3);y1=min(im.height,max(rows)+4)
  ax,ay=anchors[index]
  assert x0<=ax<x1 and y0<=ay<y1,(key,index,anchors[index])
  frames.append(dict(x=x0,y=y0,w=x1-x0,h=y1-y0,anchorX=ax,anchorY=ay,bodyHeight=body,visibleBounds=[x0+3,y0+3,x1-3,y1-3],outlines=[polygon(hull)]))
 return dict(image=image_key,path=path,width=im.width,height=im.height,facing=1,frames=frames)
def main():
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 definitions={key:register(key,spec) for key,spec in SPECS.items()}
 cast,yields=definitions.pop('fiaCasting'),definitions.pop('fiaYield')
 definitions['fia']={**cast,'frames':cast['frames']+[dict(f,image=yields['image']) for f in yields['frames']]}
 definitions['minions']={name:{**definitions['minions'],'frames':definitions['minions']['frames'][i*4:(i+1)*4]} for i,name in enumerate(('thief','guard'))}
 definitions['arena']={'panels':['arenaWest','arenaCenter','arenaEast'],'w':1536,'h':1024,'groundY':790,'overlap':.06}
 definitions['chambers']={'image':'fiaChambersBackdrop','w':1536,'h':1024,'groundY':700}
 path=ROOT/'assets/js/art-data.js';source=path.read_text(encoding='utf-8')
 block='// BEGIN ARENA ATLAS — generated by scripts/register-arena-art.py\nconst ART_ARENA='+json.dumps(definitions,separators=(',',':'))+';\n// END ARENA ATLAS'
 if '// BEGIN ARENA ATLAS' in source:
  start=source.index('// BEGIN ARENA ATLAS');end=source.index('// END ARENA ATLAS',start)+len('// END ARENA ATLAS');result=source[:start]+block+source[end:]
 else:result=source.rstrip()+'\n'+block+'\n'
 if args.check:assert source==result,'Arena registration is stale'
 else:path.write_text(result,encoding='utf-8',newline='\n')
 print('PASS: native arena alpha silhouettes and fixed body/foot registrations'+(' checked.' if args.check else ' registered.'))
if __name__=='__main__':main()

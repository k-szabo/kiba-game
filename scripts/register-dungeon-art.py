"""Register native dungeon alpha silhouettes without changing source pixels."""
import argparse,json,runpy
from pathlib import Path
import numpy as np
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
helper=runpy.run_path(str(ROOT/'scripts/register-shadow-art.py'))
components,polygon=helper['components'],helper['polygon']
SPECS={
 'captain':('dungeonCaptain',345,-1,[(332,470),(790,472),(1350,470),(403,956),(838,956),(1327,915)]),
 'necromancer':('dungeonNecromancer',425,1,[(280,505),(788,504),(1263,506),(271,995),(804,995),(1270,995)]),
 'council':('dungeonCouncil',470,-1,[(260,486),(765,494),(1280,498),(275,994),(767,992),(1275,997)])}
def actor(role,spec):
 key,body,facing,anchors=spec
 im=Image.open(ROOT/('assets/images/enemies/yomi-fall-'+role+'-v1.png'))
 assert im.mode=='RGBA'
 groups=components(np.asarray(im.getchannel('A'))>=8)
 assert len(groups)>=6 and sum(b-a for y,a,b in groups[5])>40000
 assert len(groups)==6 or sum(b-a for y,a,b in groups[6])<1000
 vertical=sorted(groups[:6],key=lambda g:sum(y*(b-a) for y,a,b in g)/sum(b-a for y,a,b in g))
 ordered=sorted(vertical[:3],key=lambda g:min(a for y,a,b in g))+sorted(vertical[3:],key=lambda g:min(a for y,a,b in g))
 frames=[]
 for index,g in enumerate(ordered):
  rows={}
  for y,a,b in g:
   old=rows.get(y,(im.width,0));rows[y]=(min(a,old[0]),max(b,old[1]))
  for other in ordered:
   if other is not g:assert all(y not in rows or b<=rows[y][0] or a>=rows[y][1] for y,a,b in other),'Neighboring pose in hull'
  x0=max(0,min(a for a,b in rows.values())-2);x1=min(im.width,max(b for a,b in rows.values())+2)
  y0=max(0,min(rows)-2);y1=min(im.height,max(rows)+3)
  ax,ay=anchors[index];assert x0<ax<x1 and y0<ay<y1
  frames.append(dict(x=x0,y=y0,w=x1-x0,h=y1-y0,anchorX=ax,anchorY=ay,bodyHeight=body,visibleBounds=[x0+2,y0+2,x1-2,y1-2],outlines=[polygon(rows)]))
 return dict(image=key,width=im.width,height=im.height,facing=facing,frames=frames)
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 data={name:actor(name,spec) for name,spec in SPECS.items()}
 data['backdrops']=[dict(panels=['dungeonCourtyardWest','dungeonCourtyardCenter','dungeonCourtyardEast'],w=1536,h=1024,groundY=720,overlap=.06),dict(image='dungeonCrypt',w=1536,h=1024),dict(image='dungeonThrones',w=1536,h=1024)]
 data['props']={'scroll':dict(image='dungeonProps',x=23,y=299,w=517,h=423,anchorX=280,anchorY=714,bodyHeight=416),'closedChest':dict(image='dungeonProps',x=536,y=333,w=484,h=359,anchorX=780,anchorY=687,bodyHeight=352),'openChest':dict(image='dungeonProps',x=1041,y=249,w=471,h=443,anchorX=1280,anchorY=687,bodyHeight=436)}
 file=ROOT/'assets/js/art-data.js';s=file.read_text(encoding='utf-8');start='// BEGIN DUNGEON ATLAS';end='// END DUNGEON ATLAS'
 block=start+' — generated by scripts/register-dungeon-art.py\nconst ART_DUNGEON='+json.dumps(data,separators=(',',':'))+';\n'+end
 if start in s:a=s.index(start);b=s.index(end,a)+len(end);out=s[:a]+block+s[b:]
 else:out=s.rstrip()+'\n'+block+'\n'
 if args.check:assert s==out,'Dungeon registration is stale'
 else:file.write_text(out,encoding='utf-8',newline='\n')
 print('PASS: three native dungeon atlases, complete isolated silhouettes, fixed body scales and foot registrations.')
if __name__=='__main__':main()

"""Register native-alpha atlases without changing source pixels."""
import hashlib
import json
from pathlib import Path
import sys
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SPECS = {
    'jailer': ('watchtowerJailerArt', 'assets/images/enemies/watchtower-jailer-v1.png'),
    'sentinel': ('watchtowerSentinelArt', 'assets/images/enemies/watchtower-sentinel-v1.png'),
    'wasp': ('giantWaspArt', 'assets/images/enemies/giant-wasp-v1.png'),
    'pilot': ('westheruArt', 'assets/images/npcs/westheru-v1.png'),
    'seal': ('westheruSealArt', 'assets/images/enemies/westheru-seal-v1.png'),
    'dragon': ('skyDragonArt', 'assets/images/enemies/sky-dragon-v1.png'),
}

def registration():
    result, hashes = {}, []
    for name, (key, file) in SPECS.items():
        image = Image.open(ROOT / file)
        assert image.mode == 'RGBA', file
        alpha = image.getchannel('A')
        assert alpha.getextrema()[0] == 0, file
        frames, heights = [], []
        for index in range(6):
            x, y = round(index % 3 * image.width / 3), round(index // 3 * image.height / 2)
            right, bottom = round((index % 3 + 1) * image.width / 3), round((index // 3 + 1) * image.height / 2)
            mask = alpha.crop((x, y, right, bottom)).point(lambda a: 255 if a > 16 else 0)
            bounds = mask.getbbox()
            assert bounds and bounds[0] > 0 and bounds[1] > 0 and bounds[2] < right-x and bounds[3] < bottom-y, (file, index, bounds)
            feet = mask.crop((0, max(0, bounds[3]-16), right-x, bounds[3])).getbbox()
            frames.append(dict(x=x, y=y, w=right-x, h=bottom-y,
                               anchorX=x+(feet[0]+feet[2])/2, anchorY=y+bounds[3],
                               visibleBounds=[x+bounds[0], y+bounds[1], x+bounds[2], y+bounds[3]]))
            heights.append(bounds[3]-bounds[1])
        for frame in frames:
            frame['bodyHeight'] = heights[0]
        result[name] = dict(image=key, facing=1, frames=frames)
        hashes.append(hashlib.sha256((ROOT / file).read_bytes()).hexdigest())
    return "/* Generated by scripts/register-watchtower-art.py; native alpha preserved; sources: " + ','.join(hashes) + " */\n'use strict';\nconst ART_WATCHTOWER=" + json.dumps(result, separators=(',', ':')) + ';\n'

target = ROOT / 'assets/js/watchtower-art-data.js'
content = registration()
if '--check' in sys.argv:
    assert target.read_text(encoding='utf-8') == content, 'Stale watchtower registration'
else:
    target.write_text(content, encoding='utf-8')

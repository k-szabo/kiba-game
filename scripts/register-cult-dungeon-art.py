"""Register approved cult dungeon sprites without changing source image pixels."""
import argparse,json,runpy
from pathlib import Path
import numpy as np
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
helper=runpy.run_path(str(ROOT/'scripts/register-shadow-art.py'))
components,polygon=helper['components'],helper['polygon']
SPECS={
 'templeGuard':('guard','cultTempleGuard',400,[(280,496),(825,497),(1300,496),(280,960),(825,960),(1305,963)]),
 'woundedAngel':('angel','cultWoundedAngel',400,[(300,501),(790,500),(1305,503),(300,983),(800,983),(1310,988)]),
 'highPriestess':('priestess','cultHighPriestess',410,[(320,495),(820,492),(1330,496),(315,989),(810,990),(1330,989)])}

def actor(spec):
 file,key,body,anchors=spec
 im=Image.open(ROOT/('assets/images/enemies/sect-fall-'+file+'-v1.png'))
 assert im.mode=='RGBA'
 alpha=np.asarray(im.getchannel('A'));assert (alpha==0).mean()>.25
 groups=components(alpha>=8)
 assert len(groups)>=6 and sum(b-a for y,a,b in groups[5])>40000
 assert len(groups)==6 or sum(b-a for y,a,b in groups[6])<1000
 vertical=sorted(groups[:6],key=lambda g:sum(y*(b-a) for y,a,b in g)/sum(b-a for y,a,b in g))
 ordered=sorted(vertical[:3],key=lambda g:min(a for y,a,b in g))+sorted(vertical[3:],key=lambda g:min(a for y,a,b in g))
 frames=[]
 for index,g in enumerate(ordered):
  rows={}
  for y,a,b in g:
   old=rows.get(y,(im.width,0));rows[y]=(min(a,old[0]),max(b,old[1]))
  for other in ordered:
   if other is not g:assert all(y not in rows or b<=rows[y][0] or a>=rows[y][1] for y,a,b in other),'Neighboring pose in hull'
  x0=max(0,min(a for a,b in rows.values())-2);x1=min(im.width,max(b for a,b in rows.values())+2)
  y0=max(0,min(rows)-2);y1=min(im.height,max(rows)+3)
  ax,ay=anchors[index];assert x0<ax<x1 and y0<ay<y1
  frames.append(dict(x=x0,y=y0,w=x1-x0,h=y1-y0,anchorX=ax,anchorY=ay,bodyHeight=body,visibleBounds=[x0+2,y0+2,x1-2,y1-2],outlines=[polygon(rows)]))
 return dict(image=key,width=im.width,height=im.height,facing=1,frames=frames)

def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 data={name:actor(spec) for name,spec in SPECS.items()}
 data['backdrops']=[dict(image='cultDungeon'+name,w=1774,h=887) for name in ('Forecourt','Hall','Sanctum')]
 file=ROOT/'assets/js/art-data.js';s=file.read_text(encoding='utf-8');start='// BEGIN CULT DUNGEON ATLAS';end='// END CULT DUNGEON ATLAS'
 block=start+' — generated by scripts/register-cult-dungeon-art.py\nconst ART_CULT_DUNGEON='+json.dumps(data,separators=(',',':'))+';\n'+end
 if start in s:a=s.index(start);b=s.index(end,a)+len(end);out=s[:a]+block+s[b:]
 else:out=s.rstrip()+'\n'+block+'\n'
 if args.check:assert s==out,'Cult dungeon registration is stale'
 else:file.write_text(out,encoding='utf-8',newline='\n')
 print('PASS: cult dungeon alpha, six isolated complete poses per boss, fixed body scales and foot registrations.')
if __name__=='__main__':main()

"""Register approved six-pose atlases; source RGBA pixels are never rewritten."""
import hashlib
import json
from pathlib import Path
import sys
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SPECS = {
    'gatekeeper': ('voidGatekeeper', 'assets/images/enemies/void-gatekeeper-v1.png', 400,
                   [(283, 460), (770, 455), (1284, 458), (242, 946), (775, 948), (1248, 948)]),
    'haru': ('haruFollow', 'assets/images/npcs/haru-follow-v1.png', 480,
             [(260, 490), (780, 489), (1290, 488), (272, 994), (785, 884), (1290, 992)]),
}

def registration():
    result, digests = {}, []
    for key, (image_key, file, body_height, anchors) in SPECS.items():
        source = ROOT / file
        image = Image.open(source)
        assert image.mode == 'RGBA', f'{file}: original alpha required'
        assert image.size == (1536, 1024), f'{file}: unexpected atlas grid'
        alpha = image.getchannel('A')
        assert alpha.getextrema()[0] == 0, f'{file}: transparent margin required'
        frames = []
        for i, (anchor_x, anchor_y) in enumerate(anchors):
            x, y = (i % 3) * 512, (i // 3) * 512
            bounds = alpha.crop((x, y, x + 512, y + 512)).point(lambda a: 255 if a > 16 else 0).getbbox()
            assert bounds, f'{file}: empty frame {i}'
            assert bounds[0] > 0 and bounds[1] > 0 and bounds[2] < 512 and bounds[3] < 512, f'{file}: clipped frame {i}'
            frames.append(dict(x=x, y=y, w=512, h=512, anchorX=anchor_x, anchorY=anchor_y,
                               bodyHeight=body_height, visibleBounds=[x+bounds[0], y+bounds[1], x+bounds[2], y+bounds[3]]))
        result[key] = dict(image=image_key, facing=1, frames=frames)
        digests.append(hashlib.sha256(source.read_bytes()).hexdigest())
    return ('/* Generated by scripts/register-descent-art.py; original alpha preserved; sources: ' + ','.join(digests) + ' */\n'
            "'use strict';\nconst ART_ZIGGURAT_DESCENT=" + json.dumps(result, separators=(',', ':')) + ';\n')

target = ROOT / 'assets/js/ziggurat-descent-art-data.js'
content = registration()
if '--check' in sys.argv:
    assert target.read_text(encoding='utf-8') == content, 'Descent atlas registration is stale'
    print('PASS: complete six-pose alpha atlases and stable body/foot anchors.')
else:
    target.write_text(content, encoding='utf-8', newline='\n')
    print('Registered descent atlases without changing source images.')
